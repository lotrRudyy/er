}

# Keep parseable lines
Write-Host "Firmware : $piFirmwareDir/$firmwareName"
Write-Host "URL      : $url"
Write-Host "Dev      : $Dev"
Write-Host "Version  : $otaVersion"
Write-Host "Build    : $otaBuild"
Write-Host "Target   : $Dev"
Write-Host "CmdNode  : $cmdNode"
Write-Host "CmdTopic : $cmdNode/cmd"
