function Get-FirmwareMainPath([string]$dev) {
    $p = Join-Path $scriptDir ("src/{0}_main.cpp" -f $dev)
    if (-not (Test-Path $p)) {
        $p2 = Join-Path $scriptDir ("src/{0}.cpp" -f $dev)
        if (Test-Path $p2) { return $p2 }
        throw "Unable to locate firmware main for '$dev'. Checked: $p and $p2"
    }
    return $p
}

function Get-FirmwareVersion([string]$dev) {
    $mainPath = Get-FirmwareMainPath $dev
    $content = Get-Content -Path $mainPath -Raw
    $match = [regex]::Match($content, 'FW_VERSION\s*=\s*"([^"]+)"')
    if (-not $match.Success) { throw "Unable to locate FW_VERSION in $mainPath" }
    return $match.Groups[1].Value
}

function Get-FirmwareBuildSeed([string]$Override) {
    if ($Override) { return $Override }
    return (Get-Date).ToString("yyyy-MM-dd_HHmmss")
}

function Get-FirmwareBuildId([string]$Seed) {
    $bytes = [System.Text.Encoding]::ASCII.GetBytes($Seed)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $hash = $sha.ComputeHash($bytes)
    $alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"
    $out = New-Object System.Text.StringBuilder
    for ($i=0; $i -lt 20; $i++) {
        $b = $hash[$i]
        [void]$out.Append($alphabet[ $b % $alphabet.Length ])
    }
    return $out.ToString()
}

function Write-FwBuildMetaHeader {
    param(
        [Parameter(Mandatory=$true)][string]$RepoRoot,
        [Parameter(Mandatory=$true)][string]$Build,
        [Parameter(Mandatory=$true)][string]$Seed
    )
    $metaPath = Join-Path $RepoRoot "src/fw_build_meta.h"
    $hdr = @"
#pragma once
// Auto-generated by er1/firmware/ota.ps1. Do not edit by hand.
#define FW_BUILD_ID_STR `"$Build`"
#define FW_BUILD_SEED_STR `"$Seed`"
"@
    Set-Content -Path $metaPath -Value $hdr -Encoding ASCII
}

# Real timeout runner; keeps tool output visible (scp progress)
function Invoke-ExeWithTimeout {
    param(
        [Parameter(Mandatory=$true)][string]$FilePath,
        [Parameter(Mandatory=$true)][string[]]$ArgumentList,
        [int]$TimeoutSec = 60,
        [string]$What = "process"
    )

    # Use Start-Process for reliable scp/ssh behavior on Windows (avoids occasional hangs with ProcessStartInfo)
    $p = Start-Process -FilePath $FilePath -ArgumentList $ArgumentList -NoNewWindow -PassThru

    $deadline = (Get-Date).AddSeconds($TimeoutSec)
    while (-not $p.HasExited) {
        Start-Sleep -Milliseconds 100
        if ((Get-Date) -gt $deadline) {
            try { Stop-Process -Id $p.Id -Force } catch {}
            throw "$What timed out after ${TimeoutSec}s"
        }
    }

    if ($p.ExitCode -ne 0) {
        throw "$What failed (exit $($p.ExitCode))"
    }
}


function Invoke-SshCapture {
    param(
        [Parameter(Mandatory=$true)][string[]]$SshArgs,
        [Parameter(Mandatory=$true)][string]$HostSpec,
        [Parameter(Mandatory=$true)][string]$RemoteCommand
    )
    $out = & ssh @SshArgs $HostSpec $RemoteCommand 2>&1
    return ($out | Out-String)
}

# =====================
