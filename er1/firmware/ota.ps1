# =====================
# VERIFY (ON PI) — cannot hang forever
# =====================
$timeoutSec = 25
Write-Host ("== Verifier(Pi): expecting hb.build={0}; watching '{1}/hb' + '{1}/ota' (up to {2}s) ==" -f $otaBuild, $cmdNode, $timeoutSec)

# Run mosquitto_sub ON THE PI (broker is there). -W sets a read-timeout so it cannot hang.
# Parse for:
#  - st=OTA_FAIL -> fail immediately
#  - hb.build == expected -> success
# If the device rolls back (your current problem), this will fail after timeout with a clear message.
$nodeLit   = $cmdNode
$expectLit = $otaBuild
$pyVerify = @'
import json, subprocess, time, sys, re

node = "__NODE__"
expect = "__EXPECT__"
timeout = int(__TIMEOUT__)

topics = [f"{node}/hb", f"{node}/ota", f"{node}/log"]
cmd = ["mosquitto_sub","-h","127.0.0.1","-v","-W","2"]
for t in topics:
    cmd += ["-t", t]

p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
start = time.time()

try:
    while True:
        if time.time() - start > timeout:
            print(f"== OTA VERIFY: FAIL (timeout; hb.build never became {expect}) within {timeout}s ==")
            sys.exit(2)

        line = p.stdout.readline()
        if not line:
            continue
        line = line.strip()
        if not line:
            continue
        print(line)

        m = re.match(r"^(\S+)\s+(.*)$", line)
        if not m:
            continue
        topic, payload = m.group(1), m.group(2)

        if topic.endswith("/ota"):
            try:
                o = json.loads(payload)
            except Exception:
                continue
            if o.get("st") == "OTA_FAIL":
                print("== OTA VERIFY: FAIL (device reported OTA_FAIL) ==")
                sys.exit(3)

        if topic.endswith("/hb"):
            try:
                hb = json.loads(payload)
            except Exception:
                continue
            b = hb.get("build")
            if b == expect:
                print("== OTA VERIFY: OK (hb.build matched) ==")
                sys.exit(0)
finally:
    try:
        p.kill()
    except Exception:
        pass
'@

# Inject values safely (avoid PowerShell interpolation issues)
$pyVerify = $pyVerify.Replace("__NODE__", $cmdNode).Replace("__EXPECT__", $otaBuild).Replace("__TIMEOUT__", "$timeoutSec")


# Write python to a temp file on the Pi and run it (avoids horrible quoting issues)
$remotePy = "/tmp/er1_ota_verify.py"
# Use a single-quoted heredoc on the Pi to avoid shell interpolation. IMPORTANT: use real newlines (`n), not "\n".
$pushPy = "cat > '$remotePy' <<'EOF'`n$pyVerify`nEOF"
$null = & ssh @sshBaseArgs "$piUser@$piHost" $pushPy
if ($LASTEXITCODE -ne 0) { throw "Failed to upload verifier script to Pi" }

$verifyOut = & ssh @sshBaseArgs "$piUser@$piHost" "python3 '$remotePy'"
Write-Host ($verifyOut | Out-String).Trim()
if ($LASTEXITCODE -ne 0) {
    throw "== OTA VERIFY: FAIL (hb.build didn't match) within ${timeoutSec}s =="
}
} finally {
    Pop-Location
