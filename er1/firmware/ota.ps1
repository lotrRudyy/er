if (-not (Test-Path $pio)) { $pio = "platformio" }
Write-Host "== Using PlatformIO: $pio =="

if (-not $NoBuild) {
    Write-Host "== Building environment '$Env' =="
    & $pio run --environment $Env
    if ($LASTEXITCODE -ne 0) { throw "Build failed" }
}

Write-Host "== Build = $otaBuild =="

# IMPORTANT: absolute firmware path so scp never breaks on cwd
$firmwarePathRel = Join-Path $scriptDir (".pio/build/{0}/firmware.bin" -f $Env)
Write-Host "== Preflight: verifying firmware exists at $firmwarePathRel =="
if (-not (Test-Path $firmwarePathRel)) { throw "Firmware not found: $firmwarePathRel" }
$firmwarePath = (Resolve-Path $firmwarePathRel).Path

# =====================
# PI / HTTP CONFIG
# =====================
$piHost = "192.168.0.10"
$piUser = "rudyy"
$piFirmwareDir = "/home/rudyy/er1/node_firmware"
$httpHost = "192.168.0.10"

$sshBaseArgs = @(
    "-o","BatchMode=yes",
    "-o","ConnectTimeout=5",
    "-o","ServerAliveInterval=2",
    "-o","ServerAliveCountMax=4"
)

# =====================
# UPLOAD
# =====================
$fwSize = (Get-Item $firmwarePath).Length
Write-Host ("== Uploading firmware to Pi as {0}  ({1} bytes) ==" -f $firmwareName, $fwSize)

& ssh @sshBaseArgs "$piUser@$piHost" "mkdir -p '$piFirmwareDir'"
if ($LASTEXITCODE -ne 0) { throw "Failed to create firmware directory on Pi at $piFirmwareDir" }

$remotePath = "$piUser@${piHost}:$piFirmwareDir/$firmwareName"
$scpArgs = @("-C") + $sshBaseArgs + @($firmwarePath, $remotePath)
$sw = [System.Diagnostics.Stopwatch]::StartNew()
Invoke-ExeWithTimeout -FilePath "scp" -ArgumentList $scpArgs -TimeoutSec 60 -What "SCP upload"
$sw.Stop()
Write-Host ("== Upload finished in {0:n2}s ==" -f $sw.Elapsed.TotalSeconds)

# =====================
# URL CHECK + SHA CHECK
# =====================
$url = ("http://{0}/node_firmware/{1}" -f $httpHost, $firmwareName).Trim()
Write-Host "== Verifying OTA URL from Pi: $url =="

& ssh @sshBaseArgs "$piUser@$piHost" "curl -fsS -o /dev/null --connect-timeout 3 --max-time 6 '$url'"
if ($LASTEXITCODE -ne 0) { throw "Pi could not reach firmware URL: $url" }

Write-Host "== Verifying HTTP-served firmware matches uploaded file (sha256) =="

$remoteFile = "$piFirmwareDir/$firmwareName"
$shaFile = Invoke-SshCapture -SshArgs $sshBaseArgs -HostSpec "$piUser@$piHost" -RemoteCommand "sha256sum '$remoteFile' | cut -c1-64"
$shaFile = $shaFile.Trim()

$shaHttp = Invoke-SshCapture -SshArgs $sshBaseArgs -HostSpec "$piUser@$piHost" -RemoteCommand "curl -fsS --connect-timeout 3 --max-time 10 '$url' | sha256sum | cut -c1-64"
$shaHttp = $shaHttp.Trim()

if (-not $shaFile -or -not $shaHttp) { throw "SHA check failed (empty hash). shaFile='$shaFile' shaHttp='$shaHttp'" }
if ($shaFile -ne $shaHttp) { throw "HTTP server is NOT serving the uploaded firmware! ($shaFile != $shaHttp)" }
Write-Host "== HTTP firmware matches uploaded file =="

# =====================
# TRIGGER OTA (PI PUBLISHER)
# =====================
Write-Host "== Triggering OTA on $cmdNode/cmd =="

$remotePublisher = "/home/rudyy/er1/scripts/ota_publish.py"
$remoteCmd = @(
    "python3", $remotePublisher,
    "--dev", $Dev,
    "--cmd-node", $cmdNode,
    "--http-host", $httpHost,
    "--version", $otaVersion,
    "--build", $otaBuild,
    "--target", $Dev,
    "--firmware-name", $firmwareName
) -join " "

$publisherOut = Invoke-SshCapture -SshArgs $sshBaseArgs -HostSpec "$piUser@$piHost" -RemoteCommand $remoteCmd
if ($LASTEXITCODE -ne 0) {
    Write-Host $publisherOut
